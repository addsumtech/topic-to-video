"""BESPOKE hero-beat components (the `component` escape hatch): a custom React/R3F file at
out_dir/bespoke/<Name>.tsx, named by scene.component, staged into the bundle + registered, and rendered
through the NORMAL render_remotion pipeline. These cover the DETERMINISTIC wiring — build_props emit,
_stage_bespoke staging + registry generation, and validate's name/file/export/dead-field/double-caption
gates. The component's visual interior is judged from rendered frames (design-critic D12), not here."""
import os
import pytest
import render_remotion as rr
import validate
import storyboard as sb

_GOOD = "export const {name} = () => null;\n"                       # a minimal valid component (named export)


def _write_component(out_dir, name, body=None):
    d = os.path.join(str(out_dir), "bespoke")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, name + ".tsx"), "w", encoding="utf-8").write(body or _GOOD.format(name=name))


def _scene(index=1, name="SpinField", **over):
    s = sb.new_scene(index, "cinematic3d", {}, narration="A bespoke hero beat line.")
    s["component"] = name
    s["componentProps"] = {"count": 48, "mode": "precess"}
    s["duration"] = 4.0
    s["audio"] = os.path.join("audio", f"{index:02d}.mp3")
    s.update(over)
    return s


def _board(out_dir, slides, **meta):
    m = {"language": "en", "aspect": "16:9", "captions": True, "fps": 30, "renderer": "remotion",
         "audacity": "conservative", "no_plan": True}
    m.update(meta)
    data = sb.new_storyboard(m)
    data["slides"] = slides
    return data


_EMPTY_REGISTRY = (
    "// AUTO-GENERATED by render_remotion._stage_bespoke — do NOT edit; rewritten every render.\n"
    "// Maps a storyboard scene's `component` name to its staged module (out_dir/bespoke/<Name>.tsx).\n"
    "// This committed default is the EMPTY map, so the bundle resolves `import ./bespoke/registry` even on a\n"
    "// checkout that has never rendered a bespoke beat. A render with `component` scenes overwrites it.\n"
    "import type React from 'react';\n"
    "export const BESPOKE: Record<string, React.FC<any>> = {};\n"
)


@pytest.fixture(autouse=True)
def _restore_registry():
    """_stage_bespoke rewrites the SHARED remotion/src/bespoke/ dir — restore its committed empty default after
    each test so the repo stays clean and no staged .tsx leaks into another test's bundle."""
    yield
    d = rr._BESPOKE_SRC
    if os.path.isdir(d):
        for fn in os.listdir(d):
            if fn.endswith(".tsx"):
                os.unlink(os.path.join(d, fn))
        open(os.path.join(d, "registry.ts"), "w", encoding="utf-8").write(_EMPTY_REGISTRY)


# ── build_props emit ──────────────────────────────────────────────────────────────────────────────────
def test_build_props_emits_component(tmp_path):
    p = rr.build_props(_board(str(tmp_path), [_scene()]), str(tmp_path))
    sc = p["scenes"][0]
    assert sc["component"] == "SpinField"
    assert sc["componentProps"] == {"count": 48, "mode": "precess"}


def test_build_props_component_props_snake_case(tmp_path):
    s = _scene(); del s["componentProps"]; s["component_props"] = {"n": 3}
    sc = rr.build_props(_board(str(tmp_path), [s]), str(tmp_path))["scenes"][0]
    assert sc["componentProps"] == {"n": 3}


def test_needs_gl_and_content_flags(tmp_path):
    # a component scene is content-bearing (not "blank") and routes to the GL path
    data = _board(str(tmp_path), [_scene()])
    assert rr.unsupported_scenes(data) == []                        # not a blank scene


# ── _stage_bespoke staging + registry generation ──────────────────────────────────────────────────────
def test_stage_generates_registry(tmp_path):
    _write_component(tmp_path, "SpinField")
    data = _board(str(tmp_path), [_scene(name="SpinField")])
    staged = rr._stage_bespoke(data, str(tmp_path))
    assert staged == ["SpinField"]
    assert os.path.isfile(os.path.join(rr._BESPOKE_SRC, "SpinField.tsx"))
    reg = open(os.path.join(rr._BESPOKE_SRC, "registry.ts")).read()
    assert "import * as _SpinField from './SpinField'" in reg
    assert "export const BESPOKE" in reg and "(_SpinField as any).default" in reg


def test_stage_empty_when_no_component(tmp_path):
    data = _board(str(tmp_path), [_scene(name="X")])
    data["slides"][0].pop("component")
    data["slides"][0]["image"] = "frames/x.png"; data["slides"][0]["type"] = "slide"
    staged = rr._stage_bespoke(data, str(tmp_path))
    assert staged == []
    assert "{}" in open(os.path.join(rr._BESPOKE_SRC, "registry.ts")).read().replace(" ", "")


def test_stage_drops_stale(tmp_path):
    # a component staged by a prior render must not linger once dropped from the board
    open(os.path.join(rr._BESPOKE_SRC, "Ghost.tsx"), "w").write("export const Ghost = () => null;")
    _write_component(tmp_path, "SpinField")
    rr._stage_bespoke(_board(str(tmp_path), [_scene(name="SpinField")]), str(tmp_path))
    assert not os.path.isfile(os.path.join(rr._BESPOKE_SRC, "Ghost.tsx"))


def test_stage_missing_file_raises(tmp_path):
    with pytest.raises(RuntimeError, match="missing"):
        rr._stage_bespoke(_board(str(tmp_path), [_scene(name="Ghost")]), str(tmp_path))


def test_stage_unsafe_name_raises(tmp_path):
    with pytest.raises(RuntimeError, match="bare identifier"):
        rr._stage_bespoke(_board(str(tmp_path), [_scene(name="../evil")]), str(tmp_path))


# ── validate wiring gates ─────────────────────────────────────────────────────────────────────────────
def test_validate_valid_component_passes(tmp_path):
    _write_component(tmp_path, "SpinField")
    r = validate.evaluate(_board(str(tmp_path), [_scene()]), str(tmp_path), pre_tts=True)
    assert r["ok"] is True
    assert not any("SpinField" in e for e in r["errors"])


def test_validate_unsafe_name_errors(tmp_path):
    r = validate.evaluate(_board(str(tmp_path), [_scene(name="foo-bar")]), str(tmp_path), pre_tts=True)
    assert r["ok"] is False and any("bare identifier" in e for e in r["errors"])


def test_validate_missing_file_errors(tmp_path):
    r = validate.evaluate(_board(str(tmp_path), [_scene(name="Ghost")]), str(tmp_path), pre_tts=True)
    assert r["ok"] is False and any("missing" in e and "Ghost" in e for e in r["errors"])


def test_validate_bad_export_errors(tmp_path):
    _write_component(tmp_path, "WrongExport", body="export const NotIt = () => null;\n")
    r = validate.evaluate(_board(str(tmp_path), [_scene(name="WrongExport")]), str(tmp_path), pre_tts=True)
    assert r["ok"] is False and any("neither a named" in e for e in r["errors"])


def test_validate_default_export_ok(tmp_path):
    _write_component(tmp_path, "Def", body="const C = () => null;\nexport default C;\n")
    r = validate.evaluate(_board(str(tmp_path), [_scene(name="Def")]), str(tmp_path), pre_tts=True)
    assert r["ok"] is True


def test_validate_dead_fields_warn(tmp_path):
    _write_component(tmp_path, "SpinField")
    s = _scene(camera3d=[{"at": 0, "yaw": 0, "radius": 12, "height": 4}])
    r = validate.evaluate(_board(str(tmp_path), [s]), str(tmp_path), pre_tts=True)
    assert r["ok"] is True                                           # dead field is a WARN, not an error
    assert any("IGNORED on a bespoke beat" in w and "camera3d" in w for w in r["warnings"])


def test_validate_self_rendered_captions_warn(tmp_path):
    _write_component(tmp_path, "SpinField",
                     body="export const SpinField = () => <Audio src={staticFile('x')} />;\n")
    r = validate.evaluate(_board(str(tmp_path), [_scene()]), str(tmp_path), pre_tts=True)
    assert any("Captions/Audio" in w for w in r["warnings"])


def test_validate_componentprops_must_be_object(tmp_path):
    _write_component(tmp_path, "SpinField")
    r = validate.evaluate(_board(str(tmp_path), [_scene(componentProps=[1, 2])]), str(tmp_path), pre_tts=True)
    assert r["ok"] is False and any("must be an object" in e for e in r["errors"])
