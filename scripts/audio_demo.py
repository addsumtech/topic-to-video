#!/usr/bin/env python3
"""A sound the viewer HEARS, for a beat whose point is a sound (`slide.audio_demo`, appended by tts.py).

    python3 scripts/audio_demo.py cancel <out.wav> [--seconds 2.5] [--gap 0.4] [--gain 0.94] [--lag-ms 0.1]

WHY. The ANC film (2026-11-05) explained noise cancelling for 157 s and never let the viewer hear it: every wave was
drawn, none was played. A product demo does the opposite — the noise, then the feature on, at matched level. `cancel`
synthesizes that A/B: a low hum (a fundamental and three harmonics — a shape, not a recording of any engine), a short
gap, then the hum plus its inverted copy scaled `gain` and `lag_ms` late, which leaves the small residual a real
canceller leaves (the sources: the waves "largely cancel"). The sidecar `<out>.json` says it is SYNTHESIZED, and when
the switch happens, so a shot can time its picture to the sound.
"""
import argparse
import json
import os
import subprocess
import sys

import numpy as np

RATE = 48000
PARTIALS = ((1, 1.0), (2, 0.42), (3, 0.22), (5, 0.12))      # the scope shot's own hum (ScopeCancel)
FUNDAMENTAL_HZ = 110.0
PEAK = 0.5                                                   # -6 dBFS: the voice is mastered to -14 LUFS around it


def _hum(n, lag_s=0.0):
    t = np.arange(n) / RATE - lag_s
    x = sum(a * np.sin(2 * np.pi * FUNDAMENTAL_HZ * k * t + 0.7 * k) for k, a in PARTIALS)
    return x / sum(a for _k, a in PARTIALS)


def synth_cancel(out, seconds=2.5, gap=0.4, gain=0.94, lag_ms=0.1):
    """Write the A/B (noise, gap, noise + anti-noise) to `out` and its sidecar; returns the sidecar dict."""
    n, g = int(seconds * RATE), int(gap * RATE)
    fade = np.minimum(1.0, np.minimum(np.arange(n), np.arange(n)[::-1]) / (0.05 * RATE))   # no clicks at the edges
    a = _hum(n) * fade
    b = (_hum(n) - gain * _hum(n, lag_ms / 1000.0)) * fade
    x = (PEAK * np.concatenate([a, np.zeros(g), b])).astype(np.float32)
    raw = out + ".f32"
    x.tofile(raw)
    try:
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "f32le", "-ar", str(RATE), "-ac", "1", "-i", raw, out],
                       check=True)
    finally:
        os.remove(raw)
    info = {"kind": "synthesized", "what": "a low hum, then the hum with its inverted copy (gain %.2f, %.1f ms late)"
            % (gain, lag_ms), "seconds": round(len(x) / RATE, 3), "switch_s": round((n + g) / RATE, 3),
            "license": "none needed: generated by scripts/audio_demo.py"}
    json.dump(info, open(out + ".json", "w"), indent=1)
    return info


def main(argv):
    ap = argparse.ArgumentParser(description="Synthesize an audio demo for slide.audio_demo")
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("cancel", help="noise, then noise + its inverted copy (a small residual)")
    c.add_argument("out")
    c.add_argument("--seconds", type=float, default=2.5)
    c.add_argument("--gap", type=float, default=0.4)
    c.add_argument("--gain", type=float, default=0.94)
    c.add_argument("--lag-ms", type=float, default=0.1)
    a = ap.parse_args(argv)
    info = synth_cancel(a.out, a.seconds, a.gap, a.gain, a.lag_ms)
    print("[audio_demo] %s — %.2f s, switches at %.2f s (%s)" % (a.out, info["seconds"], info["switch_s"], info["kind"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
