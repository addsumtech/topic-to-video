#!/usr/bin/env python3
"""gen_dna_ground — determine which shots paint their ROOT background from the Design DNA, and (re)write that set
into remotion/src/runtime/shotLuma.ts as DNA_GROUND.

Why it must exist: SHOT_LUMA is a MEASURED constant of each shot's original ground. Once a shot's ground became
`dna.bg`, that constant is wrong on a themed film — captions then contrast-pick against a luminance the frame no
longer has (dark ink on a dark ground). The fix is to recompute luminance from the DNA at render time, but ONLY for
the shots whose ground really is DNA-driven. This script derives that set from the source (never a hand-kept list),
and tests/test_remotion.py asserts the checked-in set still matches, so it cannot rot.

Usage: python scripts/gen_dna_ground.py [--check]     (--check = exit 1 if shotLuma.ts is out of date)
"""
import os, re, sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_SHOTS = os.path.join(os.path.dirname(_HERE), "remotion", "src", "shots")
_LUMA = os.path.join(os.path.dirname(_HERE), "remotion", "src", "runtime", "shotLuma.ts")
_ROOT_BG = re.compile(r"<AbsoluteFill style=\{\{\s*background:\s*([^,}]+)")


def dna_ground_shots():
    out = set()
    for f in sorted(os.listdir(_SHOTS)):
        if not f.endswith(".tsx"):
            continue
        shot = f[:-4]
        src = open(os.path.join(_SHOTS, f), encoding="utf-8").read()
        exp = src.find("export const %s" % shot)
        body = src[exp:] if exp >= 0 else src
        m = _ROOT_BG.search(body)
        if not m:
            continue
        expr = m.group(1)
        if "dna" in expr:
            out.add(shot); continue
        # one level of indirection: `background: BG` where `const BG = dna?.bg ?? …`
        for ident in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", expr):
            d = re.search(r"(?:const|let)\s+[^=\n]*\b%s\b[^=\n]*=\s*([^;\n]+)" % re.escape(ident), src)
            if d and "dna" in d.group(1):
                out.add(shot); break
    return out


def render_block(shots):
    body = ",\n  ".join(
        ", ".join(f"'{s}'" for s in shots[i:i + 6]) for i in range(0, len(shots), 6))
    return ("// Shots whose ROOT BACKGROUND is painted from the Design DNA (generated by scripts/gen_dna_ground.py;\n"
            "// tests/test_remotion.py asserts this stays in sync with the source). For these, a themed film's ground\n"
            "// luminance is a property of the DNA, not of SHOT_LUMA's measured original — see dnaGroundLum below.\n"
            "export const DNA_GROUND: ReadonlySet<string> = new Set([\n  " + body + ",\n]);\n")


def main(argv):
    shots = sorted(dna_ground_shots())
    block = render_block(shots)
    cur = open(_LUMA, encoding="utf-8").read()
    new = re.sub(r"// Shots whose ROOT BACKGROUND[\s\S]*?\]\);\n", block, cur) if "DNA_GROUND" in cur else cur + "\n" + block
    if "--check" in argv:
        ok = new == cur
        print(("DNA_GROUND up to date (%d shots)" % len(shots)) if ok else "DNA_GROUND is STALE — re-run scripts/gen_dna_ground.py")
        return 0 if ok else 1
    open(_LUMA, "w", encoding="utf-8").write(new)
    print(f"DNA_GROUND written: {len(shots)} of {len([f for f in os.listdir(_SHOTS) if f.endswith('.tsx')])} shots paint their ground from the DNA")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
