/** The luminance CLASS of an actual colour (sRGB relative luminance), so a runtime ground can be classified the
 *  same way the measured map classifies a rendered frame. Returns null for anything unparseable (a gradient
 *  string, rgba(), a css name) — callers then fall back to the measured constant. */
export const lumOf = (color?: string | null): Lum | null => {
  if (typeof color !== 'string') return null;
  const m = color.trim().replace(/^#/, '');
  if (!/^[0-9a-fA-F]{3,8}$/.test(m)) return null;
  const h = m.length === 3 || m.length === 4 ? m.slice(0, 3).split('').map((c) => c + c).join('')
          : m.length >= 6 ? m.slice(0, 6) : null;
  if (!h) return null;
  const n = parseInt(h, 16);
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  });
  const Y = 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
  return Y > 0.5 ? 'light' : Y > 0.18 ? 'mid' : 'dark';
};

/** The ground luminance a SCENE actually renders with — the value captions and seam grammar must contrast against.
 *  An explicit EDL `bgLum` still wins. Otherwise: when a Design DNA is active AND this shot paints its ground from
 *  that DNA (DNA_GROUND), the DNA's ground IS the frame's ground, so classify THAT; the measured SHOT_LUMA constant
 *  describes the shot's pre-DNA original and would be stale (that staleness rendered dark ink on a dark ground for
 *  every light-ground register that was flipped to a themed dark palette). Falls back to the measured map. */
export type GroundColors = {bg?: string | null; bgGrad?: string | null; accent?: string | null;
  accent2?: string | null; surface?: string | null};

/** Relative luminance 0..1 of a plain hex colour, or null when it is not one (e.g. a gradient string). */
export const lumValue = (color?: string | null): number | null => {
  if (typeof color !== 'string') return null;
  const m = color.trim().replace(/^#/, '');
  if (!/^[0-9a-fA-F]{3,8}$/.test(m)) return null;
  const h = m.length === 3 || m.length === 4 ? m.slice(0, 3).split('').map((c) => c + c).join('')
          : m.length >= 6 ? m.slice(0, 6) : null;
  if (!h) return null;
  const n = parseInt(h, 16);
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
};

/** The shot's ground as a NUMERIC relative luminance (0..1), or null when it cannot be resolved.
 *  The three-bucket Lum is too coarse for seam safety: EDITORIAL's bg (Y=0.005) against an accent flood
 *  (Y=0.318) is near-black against mid-orange — about 20 vs 150 once sRGB-encoded for display, a violent
 *  cut — yet it scores dark->mid, a gap of ONE, and the guard only acted at TWO. Measured on that exact
 *  seam: mean frame luminance 20.8 -> 149.3 within 100ms. Compare these numbers instead of the buckets. */
export const dnaGroundY = (shot: string, dna?: GroundColors | null): number | null => {
  const tok = DNA_GROUND_TOKEN[shot];
  if (!dna || !tok) return null;
  const names = Array.isArray(tok) ? tok : [tok];
  const ys: number[] = [];
  for (const n of names) {
    const y = lumValue(dna[n]);
    if (y === null) return null;
    ys.push(y);
  }
  return ys.reduce((a, b) => a + b, 0) / ys.length;
};

/** Perceptual (display-encoded) distance between two grounds, 0..1 — the number a seam should judge on. */
export const groundGap = (a: number | null, b: number | null): number | null =>
  a === null || b === null ? null : Math.abs(Math.pow(a, 1 / 2.2) - Math.pow(b, 1 / 2.2));

export const dnaGroundLum = (shot: string, bgLum?: Lum, dna?: GroundColors | null): Lum => {
  if (bgLum) return bgLum;
  const tok = DNA_GROUND_TOKEN[shot];
  if (dna && tok) {
    // Resolve the token(s) this shot MEASURABLY paints its ground from — averaging a two-token mix,
    // because a gradient flood's ground luminance is neither endpoint. Passing only `dna.bg` here (the
    // old signature) is what made an accent-flood shot report DARK while rendering BRIGHT.
    const names = Array.isArray(tok) ? tok : [tok];
    const ys: number[] = [];
    for (const n of names) {
      const y = lumValue(dna[n]);
      if (y === null) { ys.length = 0; break; }   // one unresolvable token ⇒ fall back, never half-guess
      ys.push(y);
    }
    if (ys.length) {
      const Y = ys.reduce((a, b) => a + b, 0) / ys.length;
      return Y > 0.5 ? 'light' : Y > 0.18 ? 'mid' : 'dark';
    }
  }
  return groundLum(shot);
};
